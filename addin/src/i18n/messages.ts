export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;
export function translator(language: Language): Translate {
  return (key, values = {}) => (language === "tr" ? tr[key] : en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
export class UiError extends Error {
  constructor(public readonly code: MessageKey) { super(tr[code]); this.name = "UiError"; }
}
export function errorText(error: unknown, t: Translate, fallback: MessageKey = "genericError"): string {
  const code = error && typeof error === "object" && "code" in error && typeof error.code === "string" ? error.code : undefined;
  const known = code && Object.hasOwn(tr, code);
  return t(known ? code as MessageKey : fallback) + (code && !known ? ` (${code})` : "");
}
